function val=V_ei(qx,qy,qz)
    b1=(5.2917721092e-11/1e-10)*2*pi*[0.25445142 0.0 0.0];
    b2=(5.2917721092e-11/1e-10)*2*pi*[0.12722571 0.22036139 0.0];
    b3=(5.2917721092e-11/1e-10)*2*pi*[0.0 0.0 0.05509035];
    
    R90=[0 -1 0;1 0 0;0 0 1];
    
    A1=R90*b1';
    B1=b1'/2;
    A2=R90*b2';
    B2=b2'/2;
    A3=b1'+b2';
    B3=[0;0;0];
    A4=R90*b2';
    B4=b2';
    A5=R90*b1';
    B5=b1';
    nm=1e-9/5.2917721092e-11;
    Z=83;
    G=2;
    
    val=0;
    if( B1(1)<qx && A3(2)/A3(1)*(qx-B3(1))+B3(2) >= qy && A4(2)/A4(1)*(qx-B4(1))+B4(2) > qy)
        val=-1/(2*pi)^3*(4*pi*Z)/((qx-b1(1))^2+(qy-b1(2))^2+qz^2+G^2);
    elseif(A2(2)/A2(1)*(qx-B2(1))+B2(2) < qy && A3(2)/A3(1)*(qx-B3(1))+B3(2) < qy && A5(2)/A5(1)*(qx-B5(1))+B5(2) < qy)
        val=-1/(2*pi)^3*(4*pi*Z)/((qx-b2(1))^2+(qy-b2(2))^2+qz^2+G^2);
    elseif( A4(2)/A4(1)*(qx-B4(1))+B4(2) <= qy && A5(2)/A5(1)*(qx-B5(1))+B5(2) > qy )
        val=-1/(2*pi)^3*(4*pi*Z)/((qx-b1(1)-b2(1))^2+(qy-b1(2)-b2(2))^2+qz^2+G^2);
%     elseif(qx==0 && qy == 0 && qz == 0)
%         val=0;
    else
        val=-1/(2*pi)^3*(4*pi*Z)/((qx)^2+(qy)^2+(qz)^2+G^2);
    end
end
